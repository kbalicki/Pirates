/**
 * City definitions for the Caribbean map.
 * Based on Sid Meier's Pirates! (2004 remake) — 45 cities, era 1680.
 *
 * Coordinate conversion from real-world to game map (Mercator projection):
 *   x = (-lonW - (-100)) / 45 * 3200    (lonW = degrees West, positive)
 *   y = (mercY(35) - mercY(lat)) / (mercY(35) - mercY(7)) * 2400
 *
 * Map bounds: 3200×2400 pixels covering 100°W–55°W, 35°N–7°N (Mercator)
 *
 * NOTE: Per-era city faction ownership configs are planned for
 * a future update. This file contains the default (1680 era) configuration.
 */

import { portId, factionId } from "../model/ids.ts";
import type { PortId, FactionId } from "../model/ids.ts";
import type { Vec2 } from "../model/WorldState.ts";

export type CitySize = "small" | "medium" | "large" | "capital";
export type WealthLevel = "poor" | "modest" | "prosperous" | "wealthy";

export type CityDef = {
  id: PortId;
  name: string;
  factionId: FactionId;
  type: "city" | "fort" | "outpost";
  pos: Vec2;
  dockRadius: number;
  marketLevel: number;
  shipyardLevel: number;
  produces: string[];
  demands: string[];
  population: CitySize;
  wealth: WealthLevel;
};

const mercY = (lat: number) => Math.log(Math.tan(Math.PI / 4 + ((lat * Math.PI) / 180) / 2));
const Y_TOP = mercY(35);
const Y_BOT = mercY(7);

/**
 * Convert real-world lon/lat to game map pixel coordinates (Mercator).
 * @param lonW Longitude in degrees West (positive, e.g. 82.4 for Havana)
 * @param lat Latitude in degrees North (positive)
 */
export function geoToMap(lonW: number, lat: number): Vec2 {
  return {
    x: Math.round(((-lonW - (-100)) / 45) * 3200),
    y: Math.round(((Y_TOP - mercY(lat)) / (Y_TOP - Y_BOT)) * 2400),
  };
}

